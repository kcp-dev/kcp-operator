// Command mock-virtualworkspace stands in for a virtual workspace server that is not kcp's own,
// so the e2e tests can exercise VirtualWorkspace.spec.command, spec.initContainers and the
// per-container kubeconfigs without depending on a real third-party server.
//
// It is a faithful stand-in in the ways the operator's contract can break:
//
//   - It declares exactly the flags the operator generates and nothing else. pflag exits on an
//     unknown flag, so if the operator ever passes a kcp-only argument to a custom server again,
//     this binary refuses to start and the pod never comes up.
//   - It serves TLS with the certificate the operator issued, on the port the operator chose.
//   - It connects to kcp with the kubeconfig it was given and reports, at /selfcheck, which
//     identity that turned out to be and what that identity may and may not do.
package main

